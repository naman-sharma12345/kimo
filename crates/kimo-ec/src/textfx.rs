/// A glyph's strokes on the 4 × 6 grid (Particle Playground's text particles, the time labels
/// of MCP contact sheets).
pub fn glyph_strokes(c: char) -> Vec<Vec<[f64; 2]>> {
    parse_glyph(c)
}

fn parse_glyph(c: char) -> Vec<Vec<[f64; 2]>> {
    glyph_src(c)
        .split(';')
        .map(|s| {
            s.split_whitespace()
                .filter_map(|pt| {
                    let (x, y) = pt.split_once(',')?;
                    Some([x.parse().ok()?, y.parse().ok()?])
                })
                .collect::<Vec<[f64; 2]>>()
        })
        .filter(|v| !v.is_empty())
        .collect()
}
